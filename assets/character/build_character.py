def fbm(P, base, octaves=4):
    out = np.zeros(P.shape[:2])
    amp, f, norm = 1.0, base, 0.0
    for o in range(octaves):
        for k in range(2):
            idx = (o * 2 + k) % len(DIRS)
            out += amp * np.sin((P @ DIRS[idx]) * f + PHS[idx])
            norm += amp
        amp *= 0.5
        f *= 2.03
    return out / norm


