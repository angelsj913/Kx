# UV unwrap per object (smart project), then uniform texel density packing
# --------------------------------------------------------------------------
def unwrap(ob):
    bpy.context.view_layer.objects.active = ob
    ob.select_set(True)
    bpy.ops.object.mode_set(mode="EDIT")
    bpy.ops.mesh.select_all(action="SELECT")
    bpy.ops.uv.smart_project(angle_limit=math.radians(66), island_margin=0.004,
                             correct_aspect=True, scale_to_bounds=False)
    bpy.ops.object.mode_set(mode="OBJECT")
    ob.select_set(False)


for ob in objs:
    unwrap(ob)


def gather_uv(ob):
    me = ob.data
    uvl = me.uv_layers.active.data
    arr = np.array([l.uv[:] for l in uvl], dtype=np.float64)
    W = sum(p.area for p in me.polygons)
    U = 0.0
    for p in me.polygons:
        idx = list(p.loop_indices)
        uv = arr[idx]
        x, y = uv[:, 0], uv[:, 1]
        U += 0.5 * abs(np.sum(x * np.roll(y, -1) - np.roll(x, -1) * y))
    return arr, W, U


MARGIN = 8.0 / TEX
items = []
for ob in objs:
    arr, W, U = gather_uv(ob)
    items.append(dict(ob=ob, uv=arr, W=W, U=U, mn=arr.min(axis=0)))


def pack(k):
    rects = []
    for it in items:
        s = math.sqrt(k * it["W"] / max(it["U"], 1e-12))
        size = ((it["uv"] - it["mn"]) * s).max(axis=0)
        rects.append((size[0], size[1], s))
    order = sorted(range(len(items)), key=lambda i: -rects[i][1])
    x = y = rowh = 0.0
    pos = {}
    for i in order:
        w, h, _ = rects[i]
        if w > 1 - 2 * MARGIN or h > 1 - 2 * MARGIN:
            return None
        if x + w + MARGIN > 1:
            x = 0.0
            y += rowh + MARGIN
            rowh = 0.0
        pos[i] = (x, y)
        x += w + MARGIN
        rowh = max(rowh, h)
    if y + rowh > 1 - MARGIN:
        return None
    return pos, rects


