# Silhouettes: front / side / back, straight from the mesh (orthographic)
def silhouettes(path):
    S, Wd, Hd = 640, 300, 720
    base_y = Hd - 40
    views = {"front": lambda p: (p.x, p.z), "side": lambda p: (p.y, p.z),
             "back": lambda p: (-p.x, p.z)}
    canvas = Image.new("RGB", (Wd * 3 + 40, Hd), (30, 30, 34))
    for i, (name, f) in enumerate(views.items()):
        img = Image.new("L", (Wd, Hd), 0)
        d = ImageDraw.Draw(img)
        for ob in objs:
            me = ob.data
            for p in me.polygons:
                pts = []
                for vi in p.vertices:
                    a, b = f(me.vertices[vi].co)
                    pts.append((Wd / 2 + a * S, base_y - b * S))
                d.polygon(pts, fill=255)
        tile = Image.merge("RGB", (img.point(lambda v: int(v * 0.85)), img, img))
        canvas.paste(tile, (i * (Wd + 20), 0))
    canvas.save(path)


