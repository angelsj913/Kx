# QA: triangle counts, manifold check, orientation (signed volume per shell)
# --------------------------------------------------------------------------
def shell_volumes(me):
    """Union-find over vertices -> each closed shell's signed volume."""
    parent = list(range(len(me.vertices)))

    def find(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    for p in me.polygons:
        vs = p.vertices
        for v in vs[1:]:
            ra, rb = find(vs[0]), find(v)
            if ra != rb:
                parent[ra] = rb
    vol = {}
    V = [v.co for v in me.vertices]
    for p in me.polygons:
        vs = p.vertices
        root = find(vs[0])
        for k in range(1, len(vs) - 1):
            a, b, c = V[vs[0]], V[vs[k]], V[vs[k + 1]]
            vol[root] = vol.get(root, 0.0) + a.dot(b.cross(c)) / 6.0
    return vol


