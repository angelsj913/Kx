def collect_triangles():
    tris = []
    for ob in objs:
        me = ob.data
        uvl = me.uv_layers.active.data
        oid = ob["mat_id"]
        for p in me.polygons:
            L = list(p.loop_indices)
            for k in range(1, len(L) - 1):
                tri = (L[0], L[k], L[k + 1])
                uv3 = np.array([uvl[t].uv[:] for t in tri], dtype=np.float64)
                p3 = np.array([me.vertices[me.loops[t].vertex_index].co[:] for t in tri],
                              dtype=np.float64)
                tris.append((uv3, p3, np.array(p.normal[:], dtype=np.float64), oid))
    return tris


