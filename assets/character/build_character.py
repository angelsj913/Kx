nrmap = np.zeros((H, W, 3), dtype=np.float64)

for uv3, p3, n, oid in collect_triangles():
    px = uv3[:, 0] * W
    py = (1.0 - uv3[:, 1]) * H
    x0, x1 = max(int(np.floor(px.min())), 0), min(int(np.ceil(px.max())), W - 1)
    y0, y1 = max(int(np.floor(py.min())), 0), min(int(np.ceil(py.max())), H - 1)
    if x1 < x0 or y1 < y0:
        continue
    xs = np.arange(x0, x1 + 1) + 0.5
    ys = np.arange(y0, y1 + 1) + 0.5
    X, Y = np.meshgrid(xs, ys)
    x1_, y1_, x2_, y2_, x3_, y3_ = px[0], py[0], px[1], py[1], px[2], py[2]
    d = (y2_ - y3_) * (x1_ - x3_) + (x3_ - x2_) * (y1_ - y3_)
    if abs(d) < 1e-12:
        continue
    l1 = ((y2_ - y3_) * (X - x3_) + (x3_ - x2_) * (Y - y3_)) / d
    l2 = ((y3_ - y1_) * (X - x3_) + (x1_ - x3_) * (Y - y3_)) / d
    l3 = 1.0 - l1 - l2
    eps = -1e-4
    m = (l1 >= eps) & (l2 >= eps) & (l3 >= eps)
    if not m.any():
        continue
    a = l1[m][:, None]
    b = l2[m][:, None]
    c = l3[m][:, None]
    pos3 = a * p3[0] + b * p3[1] + c * p3[2]
    rows = (Y[m] - 0.5).astype(int)
    cols = (X[m] - 0.5).astype(int)
    posmap[rows, cols] = pos3
    idmap[rows, cols] = oid
    nrmap[rows, cols] = n

