def _basis(t):
    """Orthonormal (u, v) perpendicular to tangent t. u prefers world X so that
    the 'rx' radius runs across the body width."""
    t = t.normalized()
    u = Vector((1, 0, 0)) - t * t.x
    if u.length < 1e-3:
        u = Vector((0, 1, 0)) - t * t.y
    u = u.normalized()
    v = t.cross(u).normalized()
    return u, v


def loft(bm, stations, segs=24):
    """stations: [(center Vector, rx, ry, tangent Vector), ...] -> closed, capped tube."""
    rings = []
    for c, rx, ry, t in stations:
        u, v = _basis(t)
        ring = []
        for k in range(segs):
            a = 2.0 * math.pi * k / segs
            ring.append(bm.verts.new(c + u * (math.cos(a) * rx) + v * (math.sin(a) * ry)))
        rings.append(ring)
    for i in range(len(rings) - 1):
        A, B = rings[i], rings[i + 1]
        for k in range(segs):
            k2 = (k + 1) % segs
            bm.faces.new((A[k], A[k2], B[k2], B[k]))
    for ring in (rings[0], rings[-1]):
        bm.faces.new(ring)
    return rings


def path_stations(pts, radii, sub=3):
    """Linear interpolation along a polyline; radii are (rx, ry) per control point."""
    pts = [Vector(p) for p in pts]
    raw = []
    for i in range(len(pts) - 1):
        for s in range(sub):
            f = s / sub
            c = pts[i].lerp(pts[i + 1], f)
            r = ((radii[i][0] * (1 - f) + radii[i + 1][0] * f),
                 (radii[i][1] * (1 - f) + radii[i + 1][1] * f))
            raw.append((c, r))
    raw.append((pts[-1], radii[-1]))
    out = []
    for j, (c, r) in enumerate(raw):
        a = raw[max(j - 1, 0)][0]
        b = raw[min(j + 1, len(raw) - 1)][0]
        t = b - a
        if t.length < 1e-9:
            t = Vector((0, 0, 1))
        out.append((c, r[0], r[1], t))
    return out


def tube(bm, pts, radii, segs=24, sub=3):
    return loft(bm, path_stations(pts, radii, sub), segs)


def ellipsoid(bm, c, r, u=32, v=16):
    res = bmesh.ops.create_uvsphere(bm, u_segments=u, v_segments=v,
                                    radius=1.0, matrix=Matrix.Identity(4))
    for vt in res["verts"]:
        vt.co = Vector((vt.co.x * r[0], vt.co.y * r[1], vt.co.z * r[2])) + Vector(c)
    return res["verts"]


def dome(bm, c, r, cut_z):
    """Upper half of an ellipsoid with a filled bottom (open helmet shell -> closed)."""
    verts = ellipsoid(bm, c, r)
    low = [vt for vt in verts if vt.co.z < cut_z]
    bmesh.ops.delete(bm, geom=low, context="VERTS")
    edges = [e for e in bm.edges if len(e.link_faces) == 1]
    if edges:
        bmesh.ops.holes_fill(bm, edges=edges, sides=0)


def new_obj(name, build_fn, mat_key):
    bm = bmesh.new()
    build_fn(bm)
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces[:])
    me = bpy.data.meshes.new(name)
    bm.to_mesh(me)
    bm.free()
    ob = bpy.data.objects.new(name, me)
    bpy.context.collection.objects.link(ob)
    for p in me.polygons:
        p.use_smooth = True
    ob["mat_id"] = IDS[mat_key]
    return ob


